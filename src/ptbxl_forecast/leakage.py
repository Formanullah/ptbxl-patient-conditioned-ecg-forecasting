"""Leakage guards (Phase 4).

Every split is patient-level, so leakage across records cannot be introduced by
splitting. These functions make the remaining channels checkable in code:

* ``assert_disjoint``: no patient (or record) in more than one partition.
* ``causality_violation``: does a transform let future samples influence the history?
* ``assert_fitted_on``: were fitted statistics computed from training records only?
* ``check_input_columns``: metadata inputs must be known at recording time. PTB-XL
  statements, flags and reports describe the whole 10 s record, including the
  forecast window, so they must not be used as model inputs.
"""

from __future__ import annotations

from collections.abc import Callable, Iterable, Mapping

import numpy as np
import pandas as pd


class LeakageError(RuntimeError):
    pass


# Known when the ECG is recorded, so allowed as model inputs.
ALLOWED_INPUT_METADATA = frozenset(
    {"age_years", "age_over_89", "sex", "height", "weight", "device", "device_family"}
)
# Derived from the full 10 s record (including the forecast window) or from its review.
FULL_RECORD_DERIVED = frozenset(
    {"scp_codes", "scp", "report", "heart_axis", "infarction_stadium1", "infarction_stadium2",
     "baseline_drift", "static_noise", "burst_noise", "electrodes_problems", "extra_beats",
     "pacemaker", "diag_superclasses", "diag_subclasses", "rhythm_codes", "form_codes",
     "validated_by", "second_opinion", "initial_autogenerated_report", "validated_by_human"}
)  # fmt: skip


def assert_disjoint(parts: Mapping[str, pd.DataFrame], key: str = "patient_id") -> None:
    """Raise if any value of ``key`` (column or 'index') occurs in two partitions."""
    seen: dict[object, str] = {}
    for name, frame in parts.items():
        values = frame.index if key == "index" else frame[key]
        for v in pd.unique(values):
            if v in seen and seen[v] != name:
                raise LeakageError(f"{key}={v} occurs in both {seen[v]!r} and {name!r}")
            seen[v] = name


def causality_violation(
    transform: Callable[[np.ndarray], np.ndarray], record: np.ndarray, history: int, seed: int = 0
) -> float:
    """Max change of ``transform(record)[:history]`` when only ``record[history:]`` changes.

    0 means the transform is causal on this record. Any positive value means the
    history it produces depends on the future.
    """
    rng = np.random.default_rng(seed)
    altered = record.copy()
    altered[history:] = altered[history:] + rng.normal(0, 1, altered[history:].shape)
    a = np.asarray(transform(record))[:history]
    b = np.asarray(transform(altered))[:history]
    return float(np.abs(a - b).max())


def assert_fitted_on(fit_ids: Iterable, train_ids: Iterable) -> None:
    """Raise if any record used for fitting is not a training record."""
    extra = set(fit_ids) - set(train_ids)
    if extra:
        raise LeakageError(
            f"{len(extra)} non-training records used for fitting, e.g. {sorted(extra)[:5]}"
        )


def check_input_columns(columns: Iterable[str]) -> None:
    """Raise unless every metadata input is known at recording time."""
    cols = set(columns)
    derived = sorted(
        c for c in cols if c in FULL_RECORD_DERIVED or c.startswith(("sc_", "q_", "rh_"))
    )
    if derived:
        raise LeakageError(f"derived from the full record incl. the forecast window: {derived}")
    unknown = sorted(cols - ALLOWED_INPUT_METADATA)
    if unknown:
        raise LeakageError(f"not on the recording-time allow-list (needs a decision): {unknown}")
